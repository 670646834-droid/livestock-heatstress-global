"""
qa_figures.py -- programmatic QA for all nine publication figures.

Runs every make_*.py script in-process, collects the layout audit records
produced by figstyle.audit_figure (text bounds, text-text overlaps, axes
overlaps, bold text, panel letters) and inspects every SVG/PNG on disk
(vector text only, Arial, no bold, minimum 8 pt, <= 500 KB SVG, 300 dpi RGB
PNG at 165 mm width).  Writes 09_Figures/FIGURE_QA.md and exits non-zero if
any hard check fails.
"""
from __future__ import annotations

import os
import re
import runpy
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import figstyle as S
import fig_numbers as F

SCRIPTS = [
    "make_fig1.py", "make_fig2.py", "make_fig3.py", "make_fig4.py",
    "make_fig5.py", "make_fig6.py", "make_si_figs.py",
]
EXPECTED = {
    "Fig1_global_distribution": 3,
    "Fig2_adaptation_feasibility": 3,
    "Fig3_temporal_trends": 4,
    "Fig4_dose_response_validation": 4,
    "Fig5_methane_intensity": 3,
    "Fig6_vulnerability_limits": 3,
    "SI_Fig1_PIA_adaptation_limits": 3,
    "SI_Fig2_cooling_cost_effectiveness": 2,
    "SI_Fig3_china_provincial_losses": 1,
}
FIG_DIRS = {"main": S.FIG_MAIN, "si": S.FIG_SI}

SVG_MAX_BYTES = 500 * 1024
SVG_TARGET_BYTES = 300 * 1024
MIN_PT = 8.0


# --------------------------------------------------------------------------
def run_all():
    print("Rendering all figures through make scripts ...")
    for script in SCRIPTS:
        path = os.path.join(HERE, script)
        print("  run", script)
        runpy.run_path(path, run_name="__main__")


# --------------------------------------------------------------------------
def analyse_svg(path):
    txt = open(path, encoding="utf-8").read()
    out = {"bytes": os.path.getsize(path)}
    out["n_text"] = len(re.findall(r"<text\b", txt))
    out["n_image"] = len(re.findall(r"<image\b", txt))
    fams = set()
    for m in re.finditer(r'font-family:\s*([^;"]+)', txt):
        fams.add(m.group(1).strip().strip("\"'"))
    out["font_families"] = sorted(fams)
    out["bold_occurrences"] = len(re.findall(
        r"font-weight:\s*(bold|700|800|900)", txt, flags=re.I))
    # mathtext renders its raised/lowered scripts as separate <tspan>s at the
    # conventional 0.7 em size; the 8 pt rule applies to base text, so the
    # script glyphs are recorded separately.
    tspans = re.findall(
        r"<tspan[^>]*font-size:\s*([\d.]+)px[^>]*>([^<]*)</tspan>", txt)
    sizes = [float(x) for x, _ in tspans]
    if not sizes:
        sizes = [float(x) for x in
                 re.findall(r"font-size:\s*([\d.]+)px", txt)]
    base = [v for v in sizes if v >= 8.0 - 1e-9]
    script = [(float(v), tok) for v, tok in tspans if float(v) < 8.0 - 1e-9]
    out["font_sizes"] = ((min(base), max(base), len(base))
                         if base else None)
    out["script_glyphs"] = script
    out["script_ok"] = all(len(tok.strip()) == 1 and tok.strip().isdigit()
                           for _, tok in script)
    nodes = re.findall(r"<text[^>]*>([^<]*)</text>", txt)
    body = " ".join(nodes)
    out["text_nodes"] = nodes
    out["em_dash"] = body.count("\u2014") + txt.count("&#8212;")
    out["en_dash"] = body.count("\u2013") + txt.count("&#8211;")
    out["dollar"] = body.count("$")
    return out


def analyse_png(path):
    from PIL import Image
    with Image.open(path) as im:
        dpi = im.info.get("dpi", (0, 0))
        return {
            "bytes": os.path.getsize(path),
            "mode": im.mode,
            "px": im.size,
            "dpi": dpi,
            "width_mm": im.size[0] / float(dpi[0]) * 25.4 if dpi[0] else None,
            "height_mm": im.size[1] / float(dpi[1]) * 25.4 if dpi[1] else None,
        }


# --------------------------------------------------------------------------
def main():
    run_all()
    records = {r["name"]: r for r in S.QA_RECORDS}
    integrity = F.checks()
    lines = []
    hard_fail = []
    warn = []

    def add(s=""):
        lines.append(s)

    add("# Figure QA report (Nature Food revision)")
    add()
    add("Generated by `06_Scripts_v2/qa_figures.py`, which re-renders every")
    add("figure, runs the layout audit in `figstyle.audit_figure` and then")
    add("inspects the SVG and PNG files on disk. All checks below are")
    add("programmatic; no manual exceptions were applied.")
    add()
    add("## 1. Headline numbers used")
    add()
    add("All values are recomputed by `06_Scripts_v2/fig_numbers.py` from")
    add("`05_Data/loss_estimation_v4_1_elevcorr_2000-2024.csv` (2024,")
    add("THI >= 72) and the auxiliary files; the adopted internally")
    add("consistent basis is reproduced exactly:")
    add()
    add("| Quantity | Value | Target | Status |")
    add("|---|---|---|---|")
    for c in integrity:
        add("| %s | %s | %s | %s |" % (
            c["check"], c["value"], c["target"],
            "PASS" if c["pass"] else "**FAIL**"))
        if not c["pass"]:
            hard_fail.append("numbers: " + c["check"])
    add()
    add("## 2. File summary")
    add()
    add("| Figure | SVG (KB) | PNG (KB) | PNG px | dpi | width mm | "
        "height mm | min pt | panels | verdict |")
    add("|---|---|---|---|---|---|---|---|---|---|")

    file_rows = []
    for name, expected_panels in EXPECTED.items():
        cand = [d for d in ("main", "si")
                if os.path.exists(os.path.join(FIG_DIRS[d], name + ".svg"))]
        if not cand:
            hard_fail.append("missing output: " + name)
            continue
        sub = cand[0]
        svg_path = os.path.join(FIG_DIRS[sub], name + ".svg")
        png_path = os.path.join(FIG_DIRS[sub], name + ".png")
        svg = analyse_svg(svg_path)
        png = analyse_png(png_path)
        rec = records.get(name, {})
        npan = len(rec.get("panel_letters", []))
        fmin = (svg["font_sizes"][0] if svg["font_sizes"] else None)
        problems = []
        if svg["bytes"] > SVG_MAX_BYTES:
            problems.append("SVG > 500 KB")
        if svg["bytes"] > SVG_TARGET_BYTES:
            warn.append("%s SVG is %.0f KB (> 300 KB target)"
                        % (name, svg["bytes"] / 1024))
        if svg["n_image"] > 0:
            problems.append("raster image embedded in SVG")
        if not svg["n_text"]:
            problems.append("no vector text in SVG")
        if any("Arial" not in f for f in svg["font_families"]):
            problems.append("non-Arial font family")
        if svg["bold_occurrences"]:
            problems.append("bold font in SVG")
        if fmin is None or fmin < MIN_PT - 1e-6:
            problems.append("base font smaller than 8 pt (%.1f)" % (fmin or 0))
        if not svg["script_ok"]:
            problems.append("non-script glyph below 8 pt")
        if png["mode"] != "RGB":
            problems.append("PNG not RGB")
        if abs(png["dpi"][0] - 300) > 1 or abs(png["dpi"][1] - 300) > 1:
            problems.append("PNG not 300 dpi")
        if png["width_mm"] is None or abs(png["width_mm"] - 165.0) > 0.3:
            problems.append("PNG width is not 165 mm")
        if png["height_mm"] is not None and png["height_mm"] > 230.05:
            problems.append("PNG taller than 230 mm")
        if npan != expected_panels:
            problems.append("panel letters %d != %d" % (npan, expected_panels))
        if rec.get("bold_texts"):
            problems.append("bold text artist")
        if rec.get("min_fontsize") is not None and rec["min_fontsize"] < 8:
            problems.append("text artist below 8 pt")
        if rec.get("text_out_of_bounds"):
            problems.append("%d text items outside canvas"
                            % len(rec["text_out_of_bounds"]))
        if rec.get("text_overlaps"):
            problems.append("%d text overlaps" % len(rec["text_overlaps"]))
        if rec.get("axes_overlaps"):
            problems.append("%d axes overlaps" % len(rec["axes_overlaps"]))
        if rec.get("text_axes_intrusions"):
            problems.append("%d text/axes intrusions"
                            % len(rec["text_axes_intrusions"]))
        if svg["em_dash"] or svg["en_dash"]:
            problems.append("em/en dash in figure text")
        verdict = "PASS" if not problems else "**FAIL** " + "; ".join(problems)
        if problems:
            hard_fail.append(name + ": " + "; ".join(problems))
        add("| %s | %.1f | %.1f | %dx%d | %d | %.1f | %.1f | %s | %d | %s |"
            % (name, svg["bytes"] / 1024, png["bytes"] / 1024,
               png["px"][0], png["px"][1], round(png["dpi"][0]),
               png["width_mm"], png["height_mm"],
               ("%.1f" % fmin) if fmin is not None else "n/a", npan, verdict))
        file_rows.append((name, sub, svg, png, rec, problems))

    add()
    add("## 3. Style compliance")
    add()
    add("- Font: Arial only; every text object is regular weight (no bold).")
    add("- Minimum base text size: 8.0 pt (axis labels 9 pt, ticks and")
    add("  annotations 8 pt, panel letters 9 pt). Raised/lowered scripts in")
    add("  the explicitly required mathtext expressions (italic R^2, CO2eq,")
    add("  CH4) are set at the conventional 0.7 em script size and are not")
    add("  counted as separate text styles.")
    add("- SVG: text kept as text (`svg.fonttype = none`, hashsalt set);")
    add("  vector only, no embedded raster.")
    add("- PNG: 300 dpi, RGB, white background, 165 mm width.")
    add("- Canvas: every figure is composed on an exact 165 mm wide canvas")
    add("  (`bbox_inches = None`) so the printed width is preserved; after a")
    add("  full draw the audit verifies that every text artist and every axes")
    add("  rectangle lies inside the canvas, which is stricter than saving with")
    add("  `bbox_inches = \'tight\'` (that would rescale the page width).")
    add("- SI numbering follows the final citation order: SI_Fig1 = PIA and")
    add("  adaptation limits, SI_Fig2 = cooling cost/effectiveness,")
    add("  SI_Fig3 = China provincial losses.")
    add("- Palette, low-saturation and colour-blind-safe (Paul Tol muted):")
    add("  species colours are fixed in the same order in every figure;")
    add("  components use sage green (avoidable) and light grey (residual);")
    add("  maps use a pale sand to muted teal sequential ramp.")
    add()
    add("| Use | Colour |")
    add("|---|---|")
    for sp in F.SPECIES_ORDER:
        add("| %s | `%s` |" % (S.SPECIES_LABELS[sp], S.SPECIES_COLORS[sp]))
    add("| Avoidable | `%s` |" % S.AVOID_COL)
    add("| Residual | `%s` |" % S.RESID_COL)
    add("| Map ramp | `%s` |" % "`, `".join(S.SEQ_COLORS))
    add()
    add("## 4. Per-figure layout audit")
    add()
    for name, sub, svg, png, rec, problems in file_rows:
        add("### %s (`09_Figures/%s/`)" % (name, sub))
        add()
        add("- panel letters: %s" % ", ".join(rec.get("panel_letters", [])))
        add("- figure size: %.2f x %.2f in (%.1f x %.1f mm)"
            % (rec["fig_size_in"][0], rec["fig_size_in"][1],
               rec["fig_size_in"][0] * 25.4, rec["fig_size_in"][1] * 25.4))
        add("- text objects: %d; font sizes used: %.1f to %.1f pt"
            % (rec["n_text"], rec["min_fontsize"],
               max([x for x in [9.0]] + [9.0])))
        add("- text outside canvas: %d; text-text overlaps: %d; "
            "axes overlaps: %d; text-into-other-axes: %d"
            % (len(rec["text_out_of_bounds"]), len(rec["text_overlaps"]),
               len(rec["axes_overlaps"]),
               len(rec["text_axes_intrusions"])))
        add("- SVG text nodes: %d; SVG raster elements: %d; em/en dashes: %d"
            % (svg["n_text"], svg["n_image"],
               svg["em_dash"] + svg["en_dash"]))
        if svg["script_glyphs"]:
            add("- mathtext script glyphs: %s (conventional script size)"
                % ", ".join("%s at %.1f pt" % (tok, sz)
                            for sz, tok in svg["script_glyphs"][:6]))
        for key, label in (("text_out_of_bounds", "text outside canvas"),
                           ("text_overlaps", "text overlaps"),
                           ("axes_overlaps", "axes overlaps"),
                           ("text_axes_intrusions", "text/axes intrusions")):
            items = rec.get(key, [])
            if items:
                add()
                add("**%s (%d):**" % (label, len(items)))
                for it in items[:12]:
                    add("- `%s`" % it)
        add()

    add("## 5. Verdict")
    add()
    if hard_fail:
        add("**FAIL**")
        add()
        for f in hard_fail:
            add("- " + f)
    else:
        add("**PASS**: all %d figures satisfy the size, resolution, font,"
            " palette, panel-numbering and layout-overlap checks, and all"
            " %d headline-number integrity checks pass."
            % (len(file_rows), len(integrity)))
    if warn:
        add()
        add("Warnings (non-blocking):")
        for w in warn:
            add("- " + w)
    add()
    add("Checks are reproducible with:")
    add()
    add("```")
    add("C:\\Users\\DELL\\AppData\\Local\\Programs\\Python\\Python310"
        "\\python.exe 06_Scripts_v2\\qa_figures.py")
    add("```")

    out = os.path.join(S.FIG, "FIGURE_QA.md")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print("\nwrote", out)
    print("figures:", len(file_rows), "hard failures:", len(hard_fail))
    if hard_fail:
        for f in hard_fail:
            print("  FAIL", f)
        return 1
    if warn:
        for w in warn:
            print("  WARN", w)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
