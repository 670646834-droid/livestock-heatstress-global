def style_row(name, sub, expected_panels):
    d = V3_MAIN if sub == "main" else V3_SI
    svg_path = os.path.join(d, name + ".svg")
    png_path = os.path.join(d, name + ".png")
    svg = Q.analyse_svg(svg_path)
    png = Q.analyse_png(png_path)
    problems = []
    if svg["bytes"] > 500 * 1024:
        problems.append("SVG > 500 KB")
    if svg["n_image"] > 0:
        problems.append("raster image in SVG")
    if not svg["n_text"]:
        problems.append("no vector text")
    if any("Arial" not in f for f in svg["font_families"]):
        problems.append("non-Arial font")
    if svg["bold_occurrences"]:
        problems.append("bold font")
    fmin = svg["font_sizes"][0] if svg["font_sizes"] else None
    if fmin is not None and fmin < 8.0 - 1e-6:
        problems.append("base font < 8 pt")
    if png["mode"] != "RGB":
        problems.append("PNG not RGB")
    if abs(png["dpi"][0] - 300) > 1:
        problems.append("PNG not 300 dpi")
    if png["width_mm"] is None or abs(png["width_mm"] - 165.0) > 0.3:
        problems.append("width not 165 mm")
    if png["height_mm"] is not None and png["height_mm"] > 230.05:
        problems.append("height > 230 mm")
    if svg["em_dash"] or svg["en_dash"]:
        problems.append("em/en dash")
    npan = expected_panels
    return {
        "name": name, "sub": sub, "svg": svg, "png": png,
        "fmin": fmin, "npan": npan,
        "problems": problems,
    }


def extract_blocks(old_md):
    """Extract per-figure audit bodies from the previous QA report."""
    blocks = {}
    parts = re.split(r"\n### ", old_md)
    for part in parts[1:]:
        header, _, body = part.partition("\n\n")
        m = re.match(r"([A-Za-z0-9_]+) \(", header)
        if m:
            blocks[m.group(1)] = body.split("\n## ")[0].rstrip() + "\n"
    return blocks


