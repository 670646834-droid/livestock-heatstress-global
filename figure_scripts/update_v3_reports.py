def main():
    rec = render_fig4()
    rows = {}
    for name, sub, npan in ORDER:
        rows[name] = style_row(name, sub, npan)
    checks = F.checks()
    fails = build_qa_md(rec, rows, checks)
    build_notes()
    print("\nQA written:", QA_MD)
    print("notes written:", NOTES_MD)
    print("figures:", len(ORDER), "fails:", len(fails), "checks:",
          sum(1 for c in checks if c["pass"]), "/", len(checks))
    for f in fails:
        print("  FAIL", f)
    return 1 if fails or any(not c["pass"] for c in checks) else 0


if __name__ == "__main__":
    raise SystemExit(main())
